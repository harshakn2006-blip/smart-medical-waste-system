
import os
import sqlite3
import sys
import psycopg

BASE_DIR = os.path.abspath(os.path.dirname(__file__))
SQLITE_DB = os.path.join(BASE_DIR, "medical_waste.db")
DATABASE_URL = os.environ.get("DATABASE_URL")

if not DATABASE_URL:
    print("ERROR: DATABASE_URL is missing.")
    sys.exit(1)

if not os.path.exists(SQLITE_DB):
    print("ERROR: medical_waste.db was not found.")
    sys.exit(1)


TABLES = {
    "users": """
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT UNIQUE NOT NULL,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL
                CHECK (role IN ('staff','collector','admin')),
            created_at TEXT NOT NULL
        )
    """,

    "waste_records": """
        CREATE TABLE IF NOT EXISTS waste_records (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            item_name TEXT NOT NULL,
            department TEXT NOT NULL,
            quantity_kg DOUBLE PRECISION NOT NULL
                CHECK (quantity_kg > 0),
            category TEXT NOT NULL,
            container TEXT NOT NULL,
            guidance TEXT NOT NULL,
            review_required SMALLINT NOT NULL DEFAULT 0,
            created_by INTEGER NOT NULL REFERENCES users(id),
            created_at TEXT NOT NULL
        )
    """,

    "collection_requests": """
        CREATE TABLE IF NOT EXISTS collection_requests (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            waste_record_id INTEGER REFERENCES waste_records(id)
                ON DELETE SET NULL,
            department TEXT NOT NULL,
            pickup_notes TEXT DEFAULT '',
            status TEXT NOT NULL DEFAULT 'Pending'
                CHECK (status IN (
                    'Pending','Assigned','Collected','Completed'
                )),
            assigned_to INTEGER REFERENCES users(id),
            requested_by INTEGER NOT NULL REFERENCES users(id),
            requested_at TEXT NOT NULL,
            updated_at TEXT NOT NULL
        )
    """,

    "image_identification_history": """
        CREATE TABLE IF NOT EXISTS image_identification_history (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            identified_item TEXT NOT NULL,
            category TEXT NOT NULL,
            container TEXT NOT NULL,
            guidance TEXT NOT NULL,
            review_required SMALLINT NOT NULL DEFAULT 1,
            identified_by INTEGER NOT NULL REFERENCES users(id),
            identified_at TEXT NOT NULL
        )
    """
}


COLUMNS = {
    "users": [
        "id", "username", "password_hash", "role", "created_at"
    ],
    "waste_records": [
        "id", "item_name", "department", "quantity_kg",
        "category", "container", "guidance",
        "review_required", "created_by", "created_at"
    ],
    "collection_requests": [
        "id", "waste_record_id", "department", "pickup_notes",
        "status", "assigned_to", "requested_by",
        "requested_at", "updated_at"
    ],
    "image_identification_history": [
        "id", "identified_item", "category", "container",
        "guidance", "review_required", "identified_by",
        "identified_at"
    ]
}


def migrate():
    sqlite_db = sqlite3.connect(SQLITE_DB)
    sqlite_db.row_factory = sqlite3.Row

    try:
        with psycopg.connect(DATABASE_URL) as pg:

            with pg.cursor() as cursor:

                print("Checking Neon database...")

                # Create tables.
                for sql in TABLES.values():
                    cursor.execute(sql)

                # Safety check: target tables must be empty.
                for table in TABLES:
                    cursor.execute(
                        f"SELECT COUNT(*) FROM {table}"
                    )

                    existing_count = cursor.fetchone()[0]

                    if existing_count > 0:
                        raise RuntimeError(
                            f"Migration stopped: {table} "
                            f"already contains {existing_count} records."
                        )

                print("Neon tables are empty. Starting migration...")

                # Copy data in foreign-key order.
                source_counts = {}

                for table, columns in COLUMNS.items():

                    column_list = ", ".join(columns)
                    placeholders = ", ".join(
                        ["%s"] * len(columns)
                    )

                    rows = sqlite_db.execute(
                        f"SELECT {column_list} FROM {table}"
                    ).fetchall()

                    source_counts[table] = len(rows)

                    for row in rows:
                        values = tuple(
                            row[column] for column in columns
                        )

                        cursor.execute(
                            f"""
                            INSERT INTO {table} ({column_list})
                            VALUES ({placeholders})
                            """,
                            values
                        )

                    print(
                        f"{table}: {len(rows)} records copied"
                    )

                # Reset PostgreSQL identity sequences.
                for table in TABLES:

                    cursor.execute(
                        f"""
                        SELECT setval(
                            pg_get_serial_sequence('{table}', 'id'),
                            COALESCE((SELECT MAX(id) FROM {table}), 1),
                            (SELECT COUNT(*) > 0 FROM {table})
                        )
                        """
                    )

                # Verify copied record counts.
                print("\nVerifying migration...")

                for table, expected_count in source_counts.items():

                    cursor.execute(
                        f"SELECT COUNT(*) FROM {table}"
                    )

                    actual_count = cursor.fetchone()[0]

                    if actual_count != expected_count:
                        raise RuntimeError(
                            f"Verification failed for {table}: "
                            f"expected {expected_count}, "
                            f"found {actual_count}"
                        )

                    print(
                        f"{table}: verified ({actual_count})"
                    )

        print("\nSUCCESS: Migration completed!")
        print("All four tables were copied and verified.")

    except Exception as error:
        print("\nMIGRATION FAILED:", repr(error))
        print("The PostgreSQL transaction was rolled back.")
        raise

    finally:
        sqlite_db.close()


if __name__ == "__main__":
    migrate()
